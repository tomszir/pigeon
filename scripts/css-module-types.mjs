// Writes a declaration beside every CSS module under the folders given, so TypeScript knows each
// module's exact class names: button.module.css gets button.module.d.css.ts. The declarations
// are generated, git-ignored, and rewritten before every typecheck.
//
//   node scripts/css-module-types.mjs apps/web/src
import { readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const WORKSPACE = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const SUFFIX = '.module.css'
const DECLARATION = '.module.d.css.ts'

function* walk(dir) {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name)
    if (statSync(path).isDirectory()) yield* walk(path)
    else yield path
  }
}

/** Class names in a stylesheet, ignoring comments, strings and url(...) where dots also appear. */
export function classNames(css) {
  const code = css
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/url\([^)]*\)/g, '')
    .replace(/"[^"]*"|'[^']*'/g, '')
  const names = new Set()
  for (const match of code.matchAll(/\.(-?[_a-zA-Z][\w-]*)/g)) names.add(match[1])
  return [...names].sort()
}

function declaration(names) {
  const keys = names.map((name) => `  readonly ${JSON.stringify(name)}: string`).join('\n')
  return `// Generated by scripts/css-module-types.mjs. Do not edit.\ndeclare const styles: {\n${keys}\n}\nexport default styles\n`
}

const roots = process.argv.slice(2)
if (roots.length === 0) {
  console.error('usage: node scripts/css-module-types.mjs <folder>...')
  process.exit(2)
}

let written = 0
for (const root of roots) {
  const files = [...walk(resolve(WORKSPACE, root))]
  // Drop declarations whose stylesheet is gone.
  for (const file of files) {
    if (file.endsWith(DECLARATION) && !files.includes(file.replace(DECLARATION, SUFFIX))) {
      rmSync(file)
    }
  }
  for (const file of files.filter((path) => path.endsWith(SUFFIX))) {
    const target = file.replace(SUFFIX, DECLARATION)
    const text = declaration(classNames(readFileSync(file, 'utf8')))
    let current = ''
    try {
      current = readFileSync(target, 'utf8')
    } catch {}
    if (current !== text) {
      writeFileSync(target, text)
      written += 1
    }
  }
}
if (written > 0) console.log(`css-module-types: wrote ${written} declarations`)
