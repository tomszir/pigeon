// Runs on Node's own test runner (mise run check), so the scripts need no test dependency.
import assert from 'node:assert/strict'
import { describe, it } from 'node:test'
import { checkAttribution, checkCommitMessage, checkHeader } from './commit-message.ts'

describe('checkHeader', () => {
  for (const header of [
    'feat: initial version',
    'fix(shell): keep the menu open while moving to All Programs',
    'feat!: drop the 800 by 600 resolution',
    'fixup! feat: initial version',
    'Revert "feat: initial version"',
  ]) {
    it(`accepts ${header}`, () => assert.deepEqual(checkHeader(header), []))
  }

  for (const [header, problem] of [
    ['Add the taskbar', 'conventional'],
    ['feature: taskbar', 'conventional'],
    ['feat:missing space', 'conventional'],
    ['feat(Shell): upper-case scope', 'conventional'],
    ['feat: Taskbar clock', 'lowercase'],
    ['feat: taskbar clock.', 'period'],
    [`feat: ${'x'.repeat(70)}`, '72'],
  ] as const) {
    it(`rejects ${header}`, () => assert.match(checkHeader(header).join(' '), new RegExp(problem)))
  }
})

describe('checkAttribution', () => {
  for (const text of [
    'Co-Authored-By: Claude <noreply@anthropic.com>',
    'co-authored-by: GitHub Copilot <copilot@github.com>',
    'Generated with Claude Code',
    'generated by ChatGPT',
    '\u{1F916} made by a robot',
  ]) {
    it(`rejects ${text}`, () => assert.notDeepEqual(checkAttribution(text), []))
  }

  for (const text of [
    'Co-Authored-By: A Person <person@example.com>',
    'Regenerated with the icon vendor script.',
  ]) {
    it(`allows ${text}`, () => assert.deepEqual(checkAttribution(text), []))
  }
})

describe('checkCommitMessage', () => {
  it('ignores git comment lines and checks the whole message', () => {
    const message =
      '# Please enter the commit message\nfix: a bug\n\nbody\n\nCo-Authored-By: Claude <x@y>\n'
    assert.deepEqual(checkCommitMessage(message), ['remove the AI Co-Authored-By trailer'])
  })

  it('rejects an empty message', () => {
    assert.deepEqual(checkCommitMessage('# only comments\n\n'), ['the commit message is empty'])
  })
})
